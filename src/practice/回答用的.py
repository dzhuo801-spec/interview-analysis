# 1. df['列'] 和 df[['列']]  差在哪？ 什么时候必须用两层？
# 两个区别很大，单层的是一维，双层是二维，而且单层的返回的是元组那种样子，而且很多情况下会崩。只有一个列的时候用单层，多个列就必须用双层
# 2. df[df['a'] > 1 & df['b'] == 'x']  为什么报错？怎么改？
# 因为你在用的是单层，你不写括号，pandas会判断你怎么用的是两列，导致会报错，必须用括号让她知道这只是一列，列出条件。
# 3. groupby(...).sum() 出来的结果里，分组列是"索引"还是"列"？
#    reset_index() 是干嘛的？
# 是索引，reset_index()是将其变成普通列
